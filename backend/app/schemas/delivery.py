"""Delivery schemas.

Weights are Decimal with 3 decimal places. In JSON, Pydantic sends Decimals as
STRINGS ("125.500") so no precision is lost in JavaScript, which only has floats.
"""
import uuid
from datetime import datetime
from decimal import Decimal
from typing import Literal

from pydantic import BaseModel, ConfigDict, Field, model_validator



class DeliveryCreate(BaseModel):
    id: uuid.UUID  # generated by the client: the idempotency key
    farmer_id: uuid.UUID
    centre_id: uuid.UUID
    crop_id: uuid.UUID
    grade_id: uuid.UUID | None = None
    season_id: uuid.UUID | None = None  # resolved from captured_at when omitted
    gross_weight: Decimal = Field(gt=0, max_digits=12, decimal_places=3)
    tare_weight: Decimal = Field(Decimal("0"), ge=0, max_digits=12, decimal_places=3)
    captured_at: datetime
    notes: str | None = Field(None, max_length=1000)
    device_id: str | None = Field(None, max_length=64)
    provisional_receipt_no: str | None = Field(None, max_length=40)

    @model_validator(mode="after")
    def check(self):
        if self.captured_at.tzinfo is None:
            raise ValueError("captured_at must include a timezone")
        if self.gross_weight - self.tare_weight <= 0:
            raise ValueError("Net weight must be greater than zero (gross must exceed tare)")
        return self


class Ref(BaseModel):
    model_config = ConfigDict(from_attributes=True)
    id: uuid.UUID
    code: str
    name: str


class FarmerRef(BaseModel):
    model_config = ConfigDict(from_attributes=True)
    id: uuid.UUID
    membership_no: str
    full_name: str
    phone: str | None


class UserRef(BaseModel):
    model_config = ConfigDict(from_attributes=True)
    id: uuid.UUID
    full_name: str


class SeasonRef(BaseModel):
    model_config = ConfigDict(from_attributes=True)
    id: uuid.UUID
    name: str


class AmendmentRead(BaseModel):
    model_config = ConfigDict(from_attributes=True)
    id: uuid.UUID
    reason: str
    old_values: dict
    new_values: dict
    status: str
    requester: UserRef
    reviewed_at: datetime | None
    review_note: str | None
    created_at: datetime


class DeliveryRead(BaseModel):
    model_config = ConfigDict(from_attributes=True)
    id: uuid.UUID
    receipt_no: str
    provisional_receipt_no: str | None
    farmer: FarmerRef
    centre: Ref
    crop: Ref
    grade: Ref | None
    season: SeasonRef
    recorder: UserRef
    gross_weight: Decimal
    tare_weight: Decimal
    net_weight: Decimal
    unit: str
    captured_at: datetime
    received_at: datetime
    source: str
    status: str
    void_reason: str | None
    voided_at: datetime | None
    notes: str | None


class DeliveryDetail(DeliveryRead):
    amendments: list[AmendmentRead]


class DeliveryCreateResult(BaseModel):
    delivery: DeliveryRead
    created: bool  # False = this id was already saved (idempotent replay)
    warnings: list[str]


class AmendmentRequest(BaseModel):
    gross_weight: Decimal | None = Field(None, gt=0, max_digits=12, decimal_places=3)
    tare_weight: Decimal | None = Field(None, ge=0, max_digits=12, decimal_places=3)
    grade_id: uuid.UUID | None = None
    notes: str | None = Field(None, max_length=1000)
    reason: str = Field(min_length=5, max_length=1000)


class AmendmentReview(BaseModel):
    decision: Literal["approve", "reject"]
    note: str | None = Field(None, max_length=1000)


class VoidRequest(BaseModel):
    reason: str = Field(min_length=5, max_length=1000)


# --- Sync ---
class SyncRequest(BaseModel):
    device_id: str = Field(min_length=1, max_length=64)
    deliveries: list[DeliveryCreate] = Field(max_length=200)


class SyncItemResult(BaseModel):
    id: uuid.UUID
    # created: saved now | duplicate: already saved earlier (safe) |
    # conflict: same id, different content (needs a manager) | rejected: failed validation
    status: Literal["created", "duplicate", "conflict", "rejected"]
    receipt_no: str | None = None
    message: str | None = None
    warnings: list[str] = []


class SyncResponse(BaseModel):
    results: list[SyncItemResult]
    server_time: datetime


class SyncFarmer(BaseModel):
    """Minimal farmer data cached on the device for offline lookup — no financial data."""
    model_config = ConfigDict(from_attributes=True)
    id: uuid.UUID
    membership_no: str
    full_name: str
    phone: str | None
    village: str | None
    home_centre_id: uuid.UUID | None
    status: str
