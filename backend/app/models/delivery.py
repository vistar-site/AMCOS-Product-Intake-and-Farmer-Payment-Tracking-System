"""Produce deliveries and their controlled amendments.

Key design points:
- id is generated by the CLIENT (phone) — it is the idempotency key for sync.
  Submitting the same id twice can never create two deliveries.
- net_weight is stored AND checked by the database: net = gross - tare, net > 0.
  Even buggy code cannot save an impossible weight.
- Deliveries are never deleted. Voiding keeps the row with a reason; weight
  corrections go through delivery_amendments, which keeps the old values forever.
- payload_hash fingerprints the original submission so a resubmission with the
  same id but DIFFERENT content is detected as a conflict, not silently accepted.
"""
import uuid
from datetime import datetime
from decimal import Decimal

from sqlalchemy import CheckConstraint, DateTime, ForeignKey, Index, Numeric, String, Text, UniqueConstraint, func
from sqlalchemy.dialects.postgresql import JSONB, UUID
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.database.base import Base, TimestampMixin
from app.models.farmer import Farmer
from app.models.reference import CollectionCentre, Crop, CropGrade, Season
from app.models.user import User

WEIGHT = Numeric(12, 3)  # up to 999,999,999.999 kg, gram precision


class Delivery(TimestampMixin, Base):
    __tablename__ = "deliveries"
    __table_args__ = (
        UniqueConstraint("organization_id", "receipt_no"),
        CheckConstraint("gross_weight > 0", name="gross_positive"),
        CheckConstraint("tare_weight >= 0", name="tare_not_negative"),
        CheckConstraint("net_weight = gross_weight - tare_weight", name="net_is_gross_minus_tare"),
        CheckConstraint("net_weight > 0", name="net_positive"),
        CheckConstraint("status IN ('recorded', 'voided')", name="status_valid"),
        CheckConstraint("source IN ('online', 'offline_sync')", name="source_valid"),
        CheckConstraint("status <> 'voided' OR void_reason IS NOT NULL", name="void_has_reason"),
        Index("ix_deliveries_org_captured", "organization_id", "captured_at"),
    )

    # No default: the caller (client device or online form) must supply the UUID.
    id: Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), primary_key=True)
    organization_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("organizations.id", ondelete="RESTRICT"), nullable=False)
    receipt_no: Mapped[str] = mapped_column(String(40), nullable=False)
    # Number printed on an offline receipt before the official one existed, e.g. OFF-3F2A-0007
    provisional_receipt_no: Mapped[str | None] = mapped_column(String(40))

    farmer_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("farmers.id", ondelete="RESTRICT"), nullable=False, index=True)
    centre_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("collection_centres.id", ondelete="RESTRICT"), nullable=False, index=True)
    crop_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("crops.id", ondelete="RESTRICT"), nullable=False, index=True)
    grade_id: Mapped[uuid.UUID | None] = mapped_column(ForeignKey("crop_grades.id", ondelete="RESTRICT"))
    season_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("seasons.id", ondelete="RESTRICT"), nullable=False, index=True)
    recorded_by: Mapped[uuid.UUID] = mapped_column(ForeignKey("users.id", ondelete="RESTRICT"), nullable=False, index=True)

    gross_weight: Mapped[Decimal] = mapped_column(WEIGHT, nullable=False)
    tare_weight: Mapped[Decimal] = mapped_column(WEIGHT, nullable=False, default=Decimal("0"), server_default="0")
    net_weight: Mapped[Decimal] = mapped_column(WEIGHT, nullable=False)
    unit: Mapped[str] = mapped_column(String(10), nullable=False, default="kg", server_default="kg")

    captured_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False)  # device clock
    received_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, server_default=func.now())  # server clock
    source: Mapped[str] = mapped_column(String(20), nullable=False, default="online")
    device_id: Mapped[str | None] = mapped_column(String(64))
    payload_hash: Mapped[str] = mapped_column(String(64), nullable=False)

    status: Mapped[str] = mapped_column(String(20), nullable=False, default="recorded", server_default="recorded")
    void_reason: Mapped[str | None] = mapped_column(Text)
    voided_by: Mapped[uuid.UUID | None] = mapped_column(ForeignKey("users.id", ondelete="RESTRICT"))
    voided_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    notes: Mapped[str | None] = mapped_column(Text)

    farmer: Mapped[Farmer] = relationship()
    centre: Mapped[CollectionCentre] = relationship()
    crop: Mapped[Crop] = relationship()
    grade: Mapped[CropGrade | None] = relationship()
    season: Mapped[Season] = relationship()
    recorder: Mapped[User] = relationship(foreign_keys=[recorded_by])
    amendments: Mapped[list["DeliveryAmendment"]] = relationship(
        back_populates="delivery", order_by="DeliveryAmendment.created_at")


class DeliveryAmendment(TimestampMixin, Base):
    """A requested correction. The clerk requests; a manager approves or rejects.
    old_values/new_values are kept permanently, so every change is explainable."""

    __tablename__ = "delivery_amendments"
    __table_args__ = (
        CheckConstraint("status IN ('pending', 'approved', 'rejected')", name="status_valid"),
    )

    id: Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    delivery_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("deliveries.id", ondelete="RESTRICT"), nullable=False, index=True)
    requested_by: Mapped[uuid.UUID] = mapped_column(ForeignKey("users.id", ondelete="RESTRICT"), nullable=False)
    reason: Mapped[str] = mapped_column(Text, nullable=False)
    old_values: Mapped[dict] = mapped_column(JSONB, nullable=False)
    new_values: Mapped[dict] = mapped_column(JSONB, nullable=False)
    status: Mapped[str] = mapped_column(String(20), nullable=False, default="pending", server_default="pending")
    reviewed_by: Mapped[uuid.UUID | None] = mapped_column(ForeignKey("users.id", ondelete="RESTRICT"))
    reviewed_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    review_note: Mapped[str | None] = mapped_column(Text)

    delivery: Mapped[Delivery] = relationship(back_populates="amendments")
    requester: Mapped[User] = relationship(foreign_keys=[requested_by])


class SyncLog(TimestampMixin, Base):
    """One row per sync request from a device: what arrived and what happened."""

    __tablename__ = "sync_logs"

    id: Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    organization_id: Mapped[uuid.UUID | None] = mapped_column(ForeignKey("organizations.id", ondelete="RESTRICT"))
    user_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("users.id", ondelete="RESTRICT"), nullable=False, index=True)
    device_id: Mapped[str | None] = mapped_column(String(64))
    received: Mapped[int] = mapped_column(nullable=False)
    created: Mapped[int] = mapped_column(nullable=False)
    duplicates: Mapped[int] = mapped_column(nullable=False)
    conflicts: Mapped[int] = mapped_column(nullable=False)
    rejected: Mapped[int] = mapped_column(nullable=False)
    details: Mapped[list] = mapped_column(JSONB, nullable=False, default=list)
